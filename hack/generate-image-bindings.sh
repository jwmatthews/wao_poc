#!/usr/bin/env bash
# Generate the tagged references the renderer matches in embedded runtime manifests.
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"
refs=$(hack/operand-image-refs.sh)
output=internal/components/zz_generated.images.go
work=$(mktemp); trap 'rm -f "$work"' EXIT
{
  echo '// Code generated by make operand-manifests from operands.yaml. DO NOT EDIT.'
  echo 'package components'
  echo 'var taggedImageReferences = map[string]string{'
  while IFS=$'\t' read -r env ref; do
    printf '\t"%s": "%s",\n' "$env" "$ref"
  done <<< "$refs"
  echo '}'
} > "$work"
gofmt -w "$work"
if ! cmp -s "$work" "$output"; then cp "$work" "$output"; fi
