#!/usr/bin/env bash
# Generate the tagged image references that the operand renderer replaces with selected pull references.
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"
RS=${RELEASE_SET:-release-set.yaml}
YQ=${YQ:-bin/yq}; [ -x "$YQ" ] || YQ=yq
output=internal/components/zz_generated.images.go
tmp=$(mktemp); trap 'rm -f "$tmp"' EXIT

{
  echo '// Code generated by make operand-manifests from release-set.yaml. DO NOT EDIT.'
  echo 'package components'
  echo 'var taggedImageReferences = map[string]string{'
  "$YQ" -o=json '[.components[].images | to_entries[]]' "$RS" | jq -r '
    if length == 0 then error("release-set has no images")
    elif any(.[]; (.value.tagged | type) != "string" or (.value.tagged | length) == 0)
      then error("each image must have a nonempty tagged reference")
    elif (map(.key) | unique | length) != length
      then error("image environment-variable names must be unique across components")
    else sort_by(.key)[] | "\t" + (.key | @json) + ": " + (.value.tagged | @json) + ","
    end'
  echo '}'
} > "$tmp"
gofmt -w "$tmp"
if ! cmp -s "$tmp" "$output"; then
  cp "$tmp" "$output"
fi
